export function resolveCatalogCharacter(
  rawCharacter: string | undefined | null,
  catalogCharacters: string[]
): string {
  if (!rawCharacter) return catalogCharacters[0] || 'Reina';
  const trimmed = rawCharacter.trim();
  if (catalogCharacters.includes(trimmed)) return trimmed;

  const lower = trimmed.toLowerCase();
  const matched = catalogCharacters.find(
    (c) =>
      c.toLowerCase() === lower ||
      lower.includes(c.toLowerCase()) ||
      c.toLowerCase().includes(lower)
  );
  return matched || catalogCharacters[0] || trimmed;
}

